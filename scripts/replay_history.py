"""Generate historical telemetry by replaying the simulator's own traffic model.

Why this exists
---------------
Modules 4 and 5 are models, and models need history. Collecting it through the live pipeline
(simulator -> Prometheus -> metrics agent -> TimescaleDB) works but takes wall-clock time:
module 4 wants about a day, and module 5 wants four weeks, because weekday-versus-weekend
prediction cannot be learned from a single week.

This script produces that history in minutes by driving `mojaloop_sim.traffic.TrafficModel`
over past timestamps. That is the *same generator* the live simulator uses, and it was
written for this - `seasonal_multiplier` is a pure function of time, and its docstring says
"a backtest over historical timestamps gives the same curve the live simulator produced".

Why not the alternatives
------------------------
* An independent random generator would teach the models a distribution the live system
  never produces, and the resulting misbehaviour looks like a detector bug rather than a
  data mismatch.
* Public AIOps datasets cannot fit `ANOMALY_FEATURES`: none of them carry
  `settlement_lag_seconds`, and `StandardScaler` fitted to another system's magnitudes makes
  every one of our normal samples read as an extreme outlier.

What this is and is not
-----------------------
It is not "real" data, but neither is anything else here - all traffic on this platform is
generated by `mojaloop_sim`. Rows are tagged `source=replay` so the difference from
pipeline-observed rows is never lost.

The rows must look like what the metrics agent stores, or a model trained on them flags
ordinary live samples. Each row is therefore built the way Prometheus builds a live one:
from the five minutes of 10-second model states before the scrape. `tps` and the error ratio
are window rates; CPU, memory, connections and the other gauges are the last instant; the
latency quantiles come from a histogram filled with the finite number of observations the
simulator records, read back with Prometheus's bucket interpolation. `--no-smooth` keeps
only the last instant (noisier than live; for experiments only).

Deliberately fault-free. An Isolation Forest trains on mostly-normal data
(`ANOMALY_CONTAMINATION` is 0.02), so the baseline should be clean and the anomalies should
come from real fault injection at demo time.

The dataset as a file
---------------------
The training set is archived as `ml/datasets/mojaloop_replay_28d.csv`. The generator is
seeded, so exporting again with the same `--end` regenerates the same rows. See docs/DATA.md.

Usage
-----
    # 28 days ending one hour ago, straight into TimescaleDB
    .\\.venv\\Scripts\\python.exe scripts\\replay_history.py --days 28

    # load the archived CSV instead (shifted by whole weeks so it ends before now)
    .\\.venv\\Scripts\\python.exe scripts\\replay_history.py --from-csv ml/datasets/mojaloop_replay_28d.csv

    # regenerate the archive
    .\\.venv\\Scripts\\python.exe scripts\\replay_history.py --export-csv ml/datasets/mojaloop_replay_28d.csv --end 2026-11-13T12:00:00+00:00

    .\\.venv\\Scripts\\python.exe scripts\\replay_history.py --clear
"""

