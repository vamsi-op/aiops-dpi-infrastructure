# Flat columns instead of the `labels` JSON blob, so the file opens cleanly in any tool.
CSV_COLUMNS = (
    *[c for c in METRIC_COLUMNS if c != "labels"],
    "source",
    "collector",
    "step_seconds",
)
_INT_COLUMNS = {"request_count", "error_count", "replicas", "step_seconds"}
_TEXT_COLUMNS = {"timestamp", "service", "instance", "platform", "source", "collector"}


def export_csv(path: Path, *, days: int, end: datetime, smooth: bool = True) -> int:
    """Write the dataset to `path`. Returns the number of rows written."""
    settings = get_settings()
    path.parent.mkdir(parents=True, exist_ok=True)
    rows = 0
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=CSV_COLUMNS, lineterminator="\n")
        writer.writeheader()
        for row in generate_rows(
            days=days,
            end=end,
            base_tps=settings.simulator.base_tps,
            seasonality=settings.simulator.seasonality,
            platform=settings.dpi_platform,
            smooth=smooth,
        ):
            labels = json.loads(row.pop("labels"))
            row["timestamp"] = row["timestamp"].isoformat()
            row["source"] = labels["source"]
            row["collector"] = labels["collector"]
            row["step_seconds"] = int(labels["step"])
            writer.writerow(row)
            rows += 1
    return rows


def read_csv(path: Path) -> Iterator[dict[str, Any]]:
    """Yield rows from an archived CSV, unshifted, in the shape INSERT_SQL expects."""
    with path.open(newline="", encoding="utf-8") as fh:
        for raw in csv.DictReader(fh):
            row: dict[str, Any] = {}
            for key, value in raw.items():
                if key in _TEXT_COLUMNS:
                    row[key] = value
                elif key in _INT_COLUMNS:
                    row[key] = int(value)
                else:
                    row[key] = float(value)
            row["timestamp"] = datetime.fromisoformat(row["timestamp"])
            row["labels"] = json.dumps(
                {
                    "source": row.pop("source"),
                    "collector": row.pop("collector"),
                    "step": str(row.pop("step_seconds")),
                    "dataset": path.name,
                }
            )
            yield row


def week_shift(last: datetime, target_end: datetime) -> timedelta:
    """Largest whole-week shift that moves `last` to on-or-before `target_end`.

    Whole weeks only: the traffic shape is a function of hour-of-day and day-of-week, and the
    live simulator keeps producing it against the real calendar. Any other shift would put
    Monday's peak on a Thursday and teach the forecaster the wrong week.
    """
    return timedelta(weeks=(target_end - last) // timedelta(weeks=1))


async def load_csv(db: Database, path: Path) -> ReplayResult:
    rows = list(read_csv(path))
    if not rows:
        raise SystemExit(f"{path} has no rows")
    shift = week_shift(rows[-1]["timestamp"], default_end())
    for row in rows:
        row["timestamp"] += shift
    log.info(
        "replay.csv_load",
        dataset=path.name,
        rows=len(rows),
        shift_days=shift.days,
        start=rows[0]["timestamp"].isoformat(),
        end=rows[-1]["timestamp"].isoformat(),
    )
    written, points = await _insert(db, iter(rows))
    return ReplayResult(
        written,
        points,
        rows[0]["timestamp"],
        rows[-1]["timestamp"],
        len({r["service"] for r in rows}),
    )


async def refresh_aggregates(db: Database, start: datetime, end: datetime) -> None:
    """Materialise both rollups across the whole replayed range.

    This is the step that is easy to omit and silently costly. Both continuous aggregate
    policies have a bounded `start_offset` - 2 hours for `service_metrics_1m` and **3 days**
    for `service_metrics_1h` - so the scheduled refresh will never touch buckets older than
    that. Replay 28 days without this and `service_metrics_1h` holds three, while
    `service_metrics` holds twenty-eight. Module 5 would train on a ninth of its data with
    every component reporting healthy.
    """
    for view in ("service_metrics_1m", "service_metrics_1h"):
        log.info("replay.refresh_start", view=view)
        # A margin at the end for the same reason the policies keep one: never materialise a
        # bucket that is still being written.
        await db.refresh_continuous_aggregate(view, start, end - timedelta(minutes=5))
        log.info("replay.refresh_done", view=view)


async def clear(db: Database) -> int:
    deleted = await db.execute(
        f"DELETE FROM {TABLE_METRICS} WHERE labels->>'source' = :source",
        {"source": REPLAY_SOURCE},
    )
    log.info("replay.cleared", rows=deleted)
    return deleted


async def report(db: Database) -> None:
    """Print what the database now holds, per producer and per rollup."""
    producers = await db.fetch_all(
        f"""
        SELECT COALESCE(labels->>'source', 'untagged') AS source,
               count(*) AS rows,
               min("timestamp") AS earliest,
               max("timestamp") AS latest
        FROM {TABLE_METRICS}
        GROUP BY 1 ORDER BY rows DESC
        """
    )
    print("\nservice_metrics by producer:")
    for row in producers:
        print(
            f"  {row['source']:14} {row['rows']:>7} rows  "
            f"{row['earliest']:%Y-%m-%d %H:%M} -> {row['latest']:%Y-%m-%d %H:%M}"
        )

    for view in ("service_metrics_1m", "service_metrics_1h"):
        stats = (
            await db.fetch_all(
                f"SELECT count(*) AS buckets, min(bucket) AS a, max(bucket) AS b FROM {view}"
            )
        )[0]
        if stats["buckets"]:
            hours = (stats["b"] - stats["a"]).total_seconds() / 3600
            print(
                f"\n{view}: {stats['buckets']} buckets over {hours / 24:.1f} days  "
                f"{stats['a']:%Y-%m-%d %H:%M} -> {stats['b']:%Y-%m-%d %H:%M}"
            )
        else:
            print(f"\n{view}: EMPTY")

    # The whole point of 28 days: a weekly rhythm the forecaster can learn. If Friday and
    # Sunday read the same, the replay did not reproduce WEEKDAY_WEIGHTS and module 5 has
    # nothing to find.
    weekly = await db.fetch_all(
        """
        SELECT EXTRACT(ISODOW FROM bucket)::int AS dow,
               round(avg(avg_tps)::numeric, 2) AS avg_tps,
               count(*) AS buckets
        FROM service_metrics_1h
        GROUP BY 1 ORDER BY 1
        """
    )
    if weekly:
        names = {1: "Mon", 2: "Tue", 3: "Wed", 4: "Thu", 5: "Fri", 6: "Sat", 7: "Sun"}
        print("\nweekly shape (mean tps per weekday, all services):")
        for row in weekly:
            bar = "#" * int(float(row["avg_tps"]) * 1.5)
            print(f"  {names[row['dow']]}  {float(row['avg_tps']):6.2f}  {bar}")


async def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--days",
        type=int,
        default=28,
        help=(
            "Days of history to generate. 28 gives four weekly cycles, so module 5 can hold "
            "one back and still train on three. Fewer than 14 cannot validate weekly "
            "seasonality at all."
        ),
    )
    parser.add_argument(
        "--clear", action="store_true", help="delete previously replayed rows and exit"
    )
    parser.add_argument(
        "--no-smooth",
        action="store_true",
        help="skip the rate5m-equivalent smoothing (leaves the series noisier than live)",
    )
    parser.add_argument(
        "--export-csv",
        type=Path,
        metavar="PATH",
        help="write the dataset to a CSV file instead of the database",
    )
    parser.add_argument(
        "--end",
        type=datetime.fromisoformat,
        metavar="ISO8601",
        help="pin the last timestamp instead of one hour ago",
    )
    parser.add_argument(
        "--from-csv",
        type=Path,
        metavar="PATH",
        help="load an archived CSV into TimescaleDB, shifted by whole weeks to end before now",
    )
    parser.add_argument(
        "--skip-refresh",
        action="store_true",
        help="do not materialise the continuous aggregates (module 5 will see almost nothing)",
    )
    args = parser.parse_args()

    if args.end is not None and args.end.tzinfo is None:
        print("--end needs a UTC offset, e.g. 2026-11-13T12:00:00+00:00")
        return 1

    if args.export_csv:
        rows = export_csv(
            args.export_csv,
            days=args.days,
            end=args.end or default_end(),
            smooth=not args.no_smooth,
        )
        print(f"Wrote {rows} rows to {args.export_csv}")
        return 0

    if args.days > 30:
        print(
            "Refusing: add_retention_policy('service_metrics', INTERVAL '30 days') would "
            "drop the oldest rows almost immediately. Use 28 or fewer."
        )
        return 1

    db = Database()
    await db.connect()
    try:
        if args.clear:
            await clear(db)
            await report(db)
            return 0

        if args.from_csv:
            result = await load_csv(db, args.from_csv)
        else:
            result = await replay(db, days=args.days, smooth=not args.no_smooth, end=args.end)
        print(
            f"\nWrote {result.rows} rows across {result.points} points "
            f"for {result.services} services."
        )
        if args.skip_refresh:
            print("Skipped aggregate refresh; service_metrics_1h will be nearly empty.")
        else:
            print("Materialising rollups across the full range (this is the slow part)...")
            await refresh_aggregates(db, result.start, result.end)
        await report(db)
        print("\nDone. The metrics agent keeps the last hour; replay owns everything before.")
        return 0
    finally:
        await db.close()


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
