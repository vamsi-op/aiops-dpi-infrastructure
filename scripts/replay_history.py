@dataclass
class ReplayResult:
    rows: int
    points: int
    start: datetime
    end: datetime
    services: int


def _normal_cdf(x: float) -> float:
    return 0.5 * (1.0 + math.erf(x / math.sqrt(2.0)))


# The rate() window of the latency quantile rules, and how many requests per second the
# simulator records into its latency histograms (`DpiMetrics.record`: one observation per
# request, capped at MAX_OBSERVATIONS_PER_TICK per one-second tick).
RATE_WINDOW_SECONDS = 300


def observations_in_window(tps: float) -> int:
    return RATE_WINDOW_SECONDS * int(min(MAX_OBSERVATIONS_PER_TICK, max(1.0, tps)))


def bucket_cdf(
    medians: Sequence[float], sigma: float, buckets: Sequence[float] = LATENCY_BUCKETS
) -> list[float]:
    """Expected cumulative share of observations at or below each bucket bound.

    The simulator observes lognormal samples (median `m`, shape `sigma`). Over a rate window
    the median drifts, so the window holds a mixture of lognormals. With log-medians that
    vary a little (the traffic drift is a few percent), that mixture is a lognormal with the
    mean log-median and shape sqrt(sigma^2 + var(log m)) - exact for normally distributed
    log-medians, and one curve instead of thirty keeps a 28-day replay to seconds.
    """
    positive = [m for m in medians if m > 0]
    if not positive:
        return [1.0 for _ in buckets]
    logs = [math.log(m) for m in positive]
    centre = math.fsum(logs) / len(logs)
    spread = math.fsum((x - centre) ** 2 for x in logs) / len(logs)
    shape = math.sqrt(max(0.0, sigma) ** 2 + spread)
    if shape <= 0:
        return [1.0 if math.log(bound) >= centre else 0.0 for bound in buckets]
    return [_normal_cdf((math.log(bound) - centre) / shape) for bound in buckets]


def _binomial(rng: random.Random, n: int, p: float) -> int:
    if n <= 0 or p <= 0.0:
        return 0
    if p >= 1.0:
        return n
    draw = getattr(rng, "binomialvariate", None)  # Python 3.12+
    if draw is not None:
        return int(draw(n, p))
    # 3.11: normal approximation, fine at the thousands of observations used here.
    return max(0, min(n, round(rng.gauss(n * p, math.sqrt(n * p * (1.0 - p))))))


def sample_cdf(cdf: Sequence[float], observations: int, rng: random.Random) -> list[float]:
    """The cumulative shares a histogram actually holds after `observations` draws.

    Multinomial over the buckets (sequential binomials), so the result carries the same
    sampling noise as the live histogram. Without it the replay's latency quantiles were an
    exact function of traffic while live ones scatter around it, and the detector read that
    ordinary scatter as anomalous.
    """
    counts, remaining, consumed = [], observations, 0.0
    for at in cdf:
        share = at - consumed
        p = share / (1.0 - consumed) if consumed < 1.0 else 0.0
        hit = _binomial(rng, remaining, min(max(p, 0.0), 1.0))
        counts.append(hit)
        remaining -= hit
        consumed = at
    total, cumulative, out = max(1, observations), 0, []
    for hit in counts:
        cumulative += hit
        out.append(cumulative / total)
    return out


def quantile_from_cdf(
    q: float, cdf: Sequence[float], buckets: Sequence[float] = LATENCY_BUCKETS
) -> float:
    """Prometheus's interpolation: linear inside the bucket holding the quantile, the first
    bucket starting at 0, and a quantile in the +Inf bucket reported as the last finite bound."""
    lower, below = 0.0, 0.0
    for upper, at in zip(buckets, cdf, strict=True):
        if at >= q:
            if at <= below:
                return upper
            return lower + (upper - lower) * (q - below) / (at - below)
        lower, below = upper, at
    return buckets[-1]


def histogram_quantile(
    q: float, medians: Sequence[float], sigma: float, buckets: Sequence[float] = LATENCY_BUCKETS
) -> float:
    """What Prometheus's `histogram_quantile(q, rate(..._bucket[5m]))` reports, in expectation.

    The live pipeline never sees the simulator's exact latency quantiles. Prometheus estimates
    each one by *linear interpolation inside the bucket* that contains it, and with wide
    buckets (0.1 s to 0.25 s) that sits well above the true value - about 15% for p99 here.
    Training on exact quantiles while scoring interpolated ones made every live sample a
    "latency spike". `observed_latencies` adds the finite-sample noise on top of this.
    """
    if not any(m > 0 for m in medians):
        return 0.0
    return quantile_from_cdf(q, bucket_cdf(medians, sigma, buckets), buckets)


# Each replay row is built the way Prometheus builds a live one: from the states of the five
# minutes before the scrape, stepped every SUB_STEP_SECONDS. `tps` and the error ratio are
# window averages (`rate(...[5m])`), the latency quantiles come from a histogram filled over
# the window, and the gauges (CPU, memory, connections, queue, settlement lag) are the last
# instant only - exactly the mix of averaged and instantaneous signals the agent stores.
SUB_STEP_SECONDS = 10
WINDOW_STATES = RATE_WINDOW_SECONDS // SUB_STEP_SECONDS


def observed_latencies(
    states: Sequence[Any], *, sigma: float, rng: random.Random | None = None
) -> dict[str, float]:
    """The five latency columns as the metrics agent reads them from Prometheus.

    Mirrors the recording rules: p50/p95/p99 of `dpi_transaction_duration_seconds`, and p95
    of the quote and verification histograms, which the simulator observes with
    `sigma * 0.8` around their own medians. `states` are the window's sub-step states.

    With `rng`, each histogram holds the finite number of observations the simulator records
    over the window (one per request, capped per tick), so quantiles carry live-like sampling
    noise. Without it they are the noise-free expectation.
    """
    if not states:
        raise ValueError("observed_latencies needs at least one state")
    observations = round(math.fsum(observations_in_window(s.tps) for s in states) / len(states))

    def quantiles(medians: list[float], shape: float, qs: tuple[float, ...]) -> list[float]:
        expected = bucket_cdf(medians, shape)
        cdf = sample_cdf(expected, observations, rng) if rng is not None else expected
        return [quantile_from_cdf(q, cdf) for q in qs]

    p50, p95, p99 = quantiles(
        [s.latency_p50_seconds for s in states], sigma, (0.50, 0.95, 0.99)
    )
    out = {
        "latency_p50_seconds": p50,
        "latency_p95_seconds": p95,
        "latency_p99_seconds": p99,
        "quote_latency_seconds": 0.0,
        "verification_latency_seconds": 0.0,
    }
    last = states[-1]
    if last.quote_latency_seconds > 0:
        out["quote_latency_seconds"] = quantiles(
            [s.quote_latency_seconds for s in states], sigma * 0.8, (0.95,)
        )[0]
    if last.verification_latency_seconds > 0:
        out["verification_latency_seconds"] = quantiles(
            [s.verification_latency_seconds for s in states], sigma * 0.8, (0.95,)
        )[0]
    return out


def window_rates(states: Sequence[Any]) -> tuple[float, float]:
    """(tps, error ratio) as `rate()` reports them over the window: the mean transaction rate,
    and failures over transactions - a traffic-weighted mean of the per-step ratios."""
    tps = math.fsum(s.tps for s in states) / len(states)
    volume = math.fsum(s.tps for s in states)
    if volume <= 0:
        return tps, 0.0
    return tps, math.fsum(s.tps * s.error_ratio for s in states) / volume


def _tiers(end: datetime, days: int) -> list[tuple[datetime, datetime, int]]:
    """Return (start, end, step) spans, oldest first."""
    fine_start = end - timedelta(days=min(FINE_TIER_DAYS, days))
    spans = []
    if days > FINE_TIER_DAYS:
        spans.append((end - timedelta(days=days), fine_start, COARSE_STEP_SECONDS))
    spans.append((fine_start, end, FINE_STEP_SECONDS))
    return spans


def _row(
    service: str,
    moment: datetime,
    state: Any,
    *,
    platform: str,
    step_seconds: int,
    tps: float,
    error_ratio: float,
    latencies: dict[str, float],
) -> dict[str, Any]:
    """Shape one row exactly as the metrics agent would.

    `request_count` counts transactions over the step and `error_count` is derived from the
    ratio, matching `MetricsCollector._counts_for`. Like the agent, the stored `error_ratio`
    is the measured ratio, not one recomputed from the rounded counts, and the latencies are
    what Prometheus's bucket interpolation reports (`observed_latencies`). Keeping the two
    producers identical is what lets a model train on one and score the other without
    learning the seam between them.
    """
    ratio = max(0.0, min(error_ratio, 1.0))
    requests = max(0, round(tps * step_seconds))
    errors = min(requests, max(0, round(requests * ratio)))
    return {
        "timestamp": moment,
        "service": service,
        "instance": f"{service}{REPLAY_INSTANCE_SUFFIX}",
        "platform": platform,
        "tps": round(tps, 4),
        "request_count": requests,
        "error_count": errors,
        "error_ratio": round(ratio, 6),
        "latency_p50_seconds": round(latencies["latency_p50_seconds"], 6),
        "latency_p95_seconds": round(latencies["latency_p95_seconds"], 6),
        "latency_p99_seconds": round(latencies["latency_p99_seconds"], 6),
        "cpu_utilisation_ratio": round(state.cpu_ratio, 5),
        "memory_utilisation_ratio": round(state.memory_ratio, 5),
        "queue_depth": round(state.queue_depth, 2),
        "active_connections": round(state.active_connections, 1),
        "settlement_lag_seconds": round(state.settlement_lag_seconds, 3),
        "quote_latency_seconds": round(latencies["quote_latency_seconds"], 6),
        "verification_latency_seconds": round(latencies["verification_latency_seconds"], 6),
        "replicas": state.replicas,
        "labels": json.dumps(
            {"source": REPLAY_SOURCE, "collector": "traffic_model", "step": str(step_seconds)}
        ),
    }


def default_end() -> datetime:
    """Stop short of now so the live agent owns the recent window (see LIVE_WINDOW_MINUTES)."""
    return (utc_now() - timedelta(minutes=LIVE_WINDOW_MINUTES)).replace(second=0, microsecond=0)


def generate_rows(
    *,
    days: int,
    end: datetime,
    base_tps: float,
    seasonality: bool,
    platform: str,
    smooth: bool = True,
) -> Iterator[dict[str, Any]]:
    """Yield replay rows oldest first. Pure: the same arguments give the same rows every run."""
    # One model per service, so the mean-reverting walk and the memory level each follow
    # their own trajectory exactly as the five live containers do.
    #
    # Seeded with crc32 rather than `hash()`, which the live simulator uses: Python
    # randomises string hashing per process unless PYTHONHASHSEED is set, so `hash(name)`
    # would give a different series on every run. That is harmless for a long-running
    # simulator but not here, where a re-run should reproduce the same history - otherwise
    # `ON CONFLICT DO NOTHING` silently keeps the first run's values while the operator
    # believes they have regenerated the data, and the archived CSV could not be verified.
    models = {
        name: TrafficModel(
            profile,
            base_tps=base_tps,
            seasonality=seasonality,
            rng=random.Random(zlib.crc32(str(name).encode())),
        )
        for name, profile in PROFILES.items()
    }
    no_faults = FaultEffects.none()
    # Histogram sampling noise gets its own seeded stream per service, so adding it leaves
    # the traffic models' random sequences - and so every other column - untouched.
    histogram_rngs = {
        name: random.Random(zlib.crc32(f"{name}:histogram".encode())) for name in PROFILES
    }

    windows: dict[str, deque[tuple[datetime, Any]]] = {
        name: deque(maxlen=WINDOW_STATES) for name in PROFILES
    }
    last_call: dict[str, datetime | None] = dict.fromkeys(PROFILES)
    sub_step = timedelta(seconds=SUB_STEP_SECONDS)

    for span_start, span_end, step in _tiers(end, days):
        moment = span_start
        while moment < span_end:
            for name, model in models.items():
                window = windows[name]
                # Advance this service's model through the sub-steps of the 5 minutes ending
                # at `moment` that it has not simulated yet. Across a coarse gap the first
                # call jumps the elapsed time in one step (the model compounds per-second
                # dynamics over it); inside the window it ticks every SUB_STEP_SECONDS.
                at = moment - (WINDOW_STATES - 1) * sub_step
                previous = last_call[name]
                while at <= moment:
                    if previous is None or at > previous:
                        elapsed = (at - previous).total_seconds() if previous else 1.0
                        window.append(
                            (at, model.sample(at, no_faults, elapsed_seconds=elapsed))
                        )
                        previous = at
                    at += sub_step
                last_call[name] = previous

                cutoff = moment - timedelta(seconds=RATE_WINDOW_SECONDS)
                states = [st for t, st in window if t > cutoff]
                if not smooth:
                    states = states[-1:]
                tps, ratio = window_rates(states)
                yield _row(
                    str(name),
                    moment,
                    states[-1],
                    platform=platform,
                    step_seconds=step,
                    tps=tps,
                    error_ratio=ratio,
                    latencies=observed_latencies(
                        states, sigma=PROFILES[name].latency_sigma, rng=histogram_rngs[name]
                    ),
                )
            moment += timedelta(seconds=step)


async def _insert(db: Database, rows: Iterator[dict[str, Any]]) -> tuple[int, int]:
    """Insert in batches. Returns (rows written, distinct timestamps)."""
    total = 0
    moments: set[datetime] = set()
    batch: list[dict[str, Any]] = []
    for row in rows:
        moments.add(row["timestamp"])
        batch.append(row)
        if len(batch) >= BATCH_ROWS:
            total += await db.execute_many(INSERT_SQL, batch)
            batch = []
            log.info("replay.progress", rows=total, up_to=row["timestamp"].isoformat())
    if batch:
        total += await db.execute_many(INSERT_SQL, batch)
    return total, len(moments)


async def replay(
    db: Database, *, days: int, smooth: bool = True, end: datetime | None = None
) -> ReplayResult:
    settings = get_settings()
    end = end or default_end()
    begin = _tiers(end, days)[0][0]
    log.info(
        "replay.start",
        days=days,
        start=begin.isoformat(),
        end=end.isoformat(),
        services=len(PROFILES),
        smoothing=smooth,
    )
    rows, points = await _insert(
        db,
        generate_rows(
            days=days,
            end=end,
            base_tps=settings.simulator.base_tps,
            seasonality=settings.simulator.seasonality,
            platform=settings.dpi_platform,
            smooth=smooth,
        ),
    )
    log.info("replay.rows_written", rows=rows, points=points)
    return ReplayResult(rows, points, begin, end, len(PROFILES))


