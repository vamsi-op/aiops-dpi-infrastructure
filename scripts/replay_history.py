"""Generate historical telemetry by replaying the simulator's own traffic model.

Why this exists
---------------
Modules 4 and 5 are models, and models need history. Collecting it through the live pipeline
(simulator -> Prometheus -> metrics agent -> TimescaleDB) works but takes wall-clock time:
module 4 wants about a day, and module 5 wants four weeks, because weekday-versus-weekend
prediction cannot be learned from a single week.

This script produces that history in minutes by driving `mojaloop_sim.traffic.TrafficModel`
over past timestamps. That is the *same generator* the live simulator uses, and it was
written for this - `seasonal_multiplier` is a pure function of time, and its docstring says
"a backtest over historical timestamps gives the same curve the live simulator produced".

Why not the alternatives
------------------------
* `seed_demo_data.py` has its own independent `random`-based generator. A model trained on it
  learns a distribution the live system never produces, and the resulting misbehaviour looks
  like a detector bug rather than a data mismatch.
* Public AIOps datasets cannot fit `ANOMALY_FEATURES`: none of them carry
  `settlement_lag_seconds`, and `StandardScaler` fitted to another system's magnitudes makes
  every one of our normal samples read as an extreme outlier.

What this is and is not
-----------------------
It is not "real" data, but neither is anything else here - all traffic on this platform is
generated by `mojaloop_sim`. The honest distinction is *pipeline-observed* versus
*directly computed*: replayed rows skip Prometheus's rate() smoothing and scrape timing, not
the traffic patterns. Rows are tagged `source=replay` so the difference is never lost, and
`--smooth` approximates the 5-minute rate window so the variance matches what the agent
would have recorded.

Deliberately fault-free. An Isolation Forest trains on mostly-normal data
(`ANOMALY_CONTAMINATION` is 0.02), so the baseline should be clean and the anomalies should
come from real fault injection at demo time.

Usage
-----
    .\\.venv\\Scripts\\python.exe scripts\\replay_history.py --days 28
    .\\.venv\\Scripts\\python.exe scripts\\replay_history.py --clear
"""

from __future__ import annotations

import argparse
import asyncio
import json
import math
import random
import sys
import zlib
from collections import deque
from dataclasses import dataclass
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any

# Allow running as a plain script from the repo root, and reach the simulator package.
_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_ROOT))
sys.path.insert(0, str(_ROOT / "services/mojaloop_sim"))

from aiops_common.config import get_settings
from aiops_common.constants import TABLE_METRICS
from aiops_common.db import Database
from aiops_common.log import configure_logging, get_logger
from aiops_common.schemas import utc_now
from mojaloop_sim.profiles import PROFILES
from mojaloop_sim.traffic import FaultEffects, TrafficModel

configure_logging("replay")
log = get_logger("replay")

# Marks every row this script writes. Distinct from the agent's `metrics-agent` so provenance
# is never ambiguous, and distinct from the seeder's `seed-` instance prefix so `--clear` can
# remove exactly these rows.
REPLAY_SOURCE = "replay"
REPLAY_INSTANCE_SUFFIX = ":replay"

# Resolution tiers, coarse for old data and fine for recent.
#
# The boundary is not arbitrary: `add_compression_policy('service_metrics', INTERVAL '2
# days')` compresses anything older, so the fine-grained tier is exactly the range that stays
# uncompressed and cheap to query. Module 4 needs the fine resolution; module 5 reads the
# 1-hour rollup, for which four samples an hour is ample.
FINE_TIER_DAYS = 2
FINE_STEP_SECONDS = 60
COARSE_STEP_SECONDS = 900

# Stop short of now and let the live agent own the recent window.
#
# This is a correctness requirement, not tidiness. `DashboardRepository.service_health` sums
# `tps` across a service's instances within a 120-second grace window, so replay rows and
# agent rows for the same service inside that window would double the platform's reported
# traffic with nothing to explain it. One hour is comfortably clear of the grace period.
LIVE_WINDOW_MINUTES = 60

# Rows per insert batch. A 28-day replay is ~27k rows; one transaction that size holds locks
# on the hypertable long enough to stall live collection.
BATCH_ROWS = 2_000

METRIC_COLUMNS = (
    "timestamp",
    "service",
    "instance",
    "platform",
    "tps",
    "request_count",
    "error_count",
    "error_ratio",
    "latency_p50_seconds",
    "latency_p95_seconds",
    "latency_p99_seconds",
    "cpu_utilisation_ratio",
    "memory_utilisation_ratio",
    "queue_depth",
    "active_connections",
    "settlement_lag_seconds",
    "quote_latency_seconds",
    "verification_latency_seconds",
    "replicas",
    "labels",
)

_VALUES = ", ".join(
    f"CAST(:{c} AS jsonb)" if c == "labels" else f":{c}" for c in METRIC_COLUMNS
)

INSERT_SQL = f"""
INSERT INTO {TABLE_METRICS} ({", ".join(f'"{c}"' for c in METRIC_COLUMNS)})
VALUES ({_VALUES})
ON CONFLICT ("timestamp", service, instance) DO NOTHING
"""


@dataclass
class ReplayResult:
    rows: int
    points: int
    start: datetime
    end: datetime
    services: int


class Smoother:
    """Approximates Prometheus's 5-minute rate window with a trailing mean.

    Without this, replayed rows are noisier than agent-collected rows: `TrafficModel.sample`
    is instantaneous while `dpi:tps:rate5m` is a five-minute average. A model fitted on the
    unsmoothed series would learn a variance the live data does not have, and would then find
    live data suspiciously *calm* - the opposite of the intended behaviour.
    """

    def __init__(self, step_seconds: int, window_seconds: int = 300) -> None:
        self._size = max(1, round(window_seconds / step_seconds))
        self._history: dict[str, deque[float]] = {}

    def __call__(self, key: str, value: float) -> float:
        window = self._history.setdefault(key, deque(maxlen=self._size))
        window.append(value)
        return math.fsum(window) / len(window)

    @property
    def size(self) -> int:
        return self._size


def _tiers(end: datetime, days: int) -> list[tuple[datetime, datetime, int]]:
    """Return (start, end, step) spans, oldest first."""
    fine_start = end - timedelta(days=min(FINE_TIER_DAYS, days))
    spans = []
    if days > FINE_TIER_DAYS:
        spans.append((end - timedelta(days=days), fine_start, COARSE_STEP_SECONDS))
    spans.append((fine_start, end, FINE_STEP_SECONDS))
    return spans


def _row(
    service: str,
    moment: datetime,
    state: Any,
    *,
    platform: str,
    step_seconds: int,
    tps: float,
    error_ratio: float,
) -> dict[str, Any]:
    """Shape one row exactly as the metrics agent would.

    `request_count` counts transactions over the step and `error_count` is derived from the
    ratio, matching `MetricsCollector._counts_for`. Keeping the two producers identical is
    what lets a model train across both without learning the seam between them.
    """
    requests = max(0, round(tps * step_seconds))
    errors = min(requests, max(0, round(requests * max(0.0, min(error_ratio, 1.0)))))
    return {
        "timestamp": moment,
        "service": service,
        "instance": f"{service}{REPLAY_INSTANCE_SUFFIX}",
        "platform": platform,
        "tps": round(tps, 4),
        "request_count": requests,
        "error_count": errors,
        "error_ratio": round(errors / requests, 6) if requests else 0.0,
        "latency_p50_seconds": round(state.latency_p50_seconds, 6),
        "latency_p95_seconds": round(state.latency_p95_seconds, 6),
        "latency_p99_seconds": round(state.latency_p99_seconds, 6),
        "cpu_utilisation_ratio": round(state.cpu_ratio, 5),
        "memory_utilisation_ratio": round(state.memory_ratio, 5),
        "queue_depth": round(state.queue_depth, 2),
        "active_connections": round(state.active_connections, 1),
        "settlement_lag_seconds": round(state.settlement_lag_seconds, 3),
        "quote_latency_seconds": round(state.quote_latency_seconds, 6),
        "verification_latency_seconds": round(state.verification_latency_seconds, 6),
        "replicas": state.replicas,
        "labels": json.dumps(
            {"source": REPLAY_SOURCE, "collector": "traffic_model", "step": str(step_seconds)}
        ),
    }


async def replay(db: Database, *, days: int, smooth: bool = True) -> ReplayResult:
    settings = get_settings()
    end = (utc_now() - timedelta(minutes=LIVE_WINDOW_MINUTES)).replace(second=0, microsecond=0)
    spans = _tiers(end, days)
    begin = spans[0][0]

    log.info(
        "replay.start",
        days=days,
        start=begin.isoformat(),
        end=end.isoformat(),
        services=len(PROFILES),
        smoothing=smooth,
    )

    total_rows = 0
    total_points = 0

    # One model per service, so the mean-reverting walk and the memory level each follow
    # their own trajectory exactly as the five live containers do.
    #
    # Seeded with crc32 rather than `hash()`, which the live simulator uses: Python
    # randomises string hashing per process unless PYTHONHASHSEED is set, so `hash(name)`
    # would give a different series on every run. That is harmless for a long-running
    # simulator but not here, where a re-run should reproduce the same history - otherwise
    # `ON CONFLICT DO NOTHING` silently keeps the first run's values while the operator
    # believes they have regenerated the data.
    models = {
        name: TrafficModel(
            profile,
            base_tps=settings.simulator.base_tps,
            seasonality=settings.simulator.seasonality,
            rng=random.Random(zlib.crc32(str(name).encode())),
        )
        for name, profile in PROFILES.items()
    }
    no_faults = FaultEffects.none()
    batch: list[dict[str, Any]] = []

    for span_start, span_end, step in spans:
        smoother = Smoother(step) if smooth else None
        if smoother is not None:
            log.info(
                "replay.tier",
                start=span_start.isoformat(),
                end=span_end.isoformat(),
                step_seconds=step,
                smoothing_window=smoother.size,
            )

        moment = span_start
        while moment < span_end:
            for name, model in models.items():
                state = model.sample(moment, no_faults)
                tps = state.tps
                ratio = state.error_ratio
                if smoother is not None:
                    tps = smoother(f"{name}:tps", state.tps)
                    ratio = smoother(f"{name}:err", state.error_ratio)
                batch.append(
                    _row(
                        str(name),
                        moment,
                        state,
                        platform=settings.dpi_platform,
                        step_seconds=step,
                        tps=tps,
                        error_ratio=ratio,
                    )
                )
            total_points += 1

            if len(batch) >= BATCH_ROWS:
                total_rows += await db.execute_many(INSERT_SQL, batch)
                batch = []
                log.info("replay.progress", rows=total_rows, up_to=moment.isoformat())

            moment += timedelta(seconds=step)

    if batch:
        total_rows += await db.execute_many(INSERT_SQL, batch)

    log.info("replay.rows_written", rows=total_rows, points=total_points)
    return ReplayResult(total_rows, total_points, begin, end, len(models))


async def refresh_aggregates(db: Database, start: datetime, end: datetime) -> None:
    """Materialise both rollups across the whole replayed range.

    This is the step that is easy to omit and silently costly. Both continuous aggregate
    policies have a bounded `start_offset` - 2 hours for `service_metrics_1m` and **3 days**
    for `service_metrics_1h` - so the scheduled refresh will never touch buckets older than
    that. Replay 28 days without this and `service_metrics_1h` holds three, while
    `service_metrics` holds twenty-eight. Module 5 would train on a ninth of its data with
    every component reporting healthy.
    """
    for view in ("service_metrics_1m", "service_metrics_1h"):
        log.info("replay.refresh_start", view=view)
        # A margin at the end for the same reason the policies keep one: never materialise a
        # bucket that is still being written.
        await db.refresh_continuous_aggregate(view, start, end - timedelta(minutes=5))
        log.info("replay.refresh_done", view=view)


async def clear(db: Database) -> int:
    deleted = await db.execute(
        f"DELETE FROM {TABLE_METRICS} WHERE labels->>'source' = :source",
        {"source": REPLAY_SOURCE},
    )
    log.info("replay.cleared", rows=deleted)
    return deleted


async def report(db: Database) -> None:
    """Print what the database now holds, per producer and per rollup."""
    producers = await db.fetch_all(
        f"""
        SELECT COALESCE(labels->>'source', 'untagged') AS source,
               count(*) AS rows,
               min("timestamp") AS earliest,
               max("timestamp") AS latest
        FROM {TABLE_METRICS}
        GROUP BY 1 ORDER BY rows DESC
        """
    )
    print("\nservice_metrics by producer:")
    for row in producers:
        print(
            f"  {row['source']:14} {row['rows']:>7} rows  "
            f"{row['earliest']:%Y-%m-%d %H:%M} -> {row['latest']:%Y-%m-%d %H:%M}"
        )

    for view in ("service_metrics_1m", "service_metrics_1h"):
        stats = (
            await db.fetch_all(
                f"SELECT count(*) AS buckets, min(bucket) AS a, max(bucket) AS b FROM {view}"
            )
        )[0]
        if stats["buckets"]:
            hours = (stats["b"] - stats["a"]).total_seconds() / 3600
            print(
                f"\n{view}: {stats['buckets']} buckets over {hours / 24:.1f} days  "
                f"{stats['a']:%Y-%m-%d %H:%M} -> {stats['b']:%Y-%m-%d %H:%M}"
            )
        else:
            print(f"\n{view}: EMPTY")

    # The whole point of 28 days: a weekly rhythm the forecaster can learn. If Friday and
    # Sunday read the same, the replay did not reproduce WEEKDAY_WEIGHTS and module 5 has
    # nothing to find.
    weekly = await db.fetch_all(
        """
        SELECT EXTRACT(ISODOW FROM bucket)::int AS dow,
               round(avg(avg_tps)::numeric, 2) AS avg_tps,
               count(*) AS buckets
        FROM service_metrics_1h
        GROUP BY 1 ORDER BY 1
        """
    )
    if weekly:
        names = {1: "Mon", 2: "Tue", 3: "Wed", 4: "Thu", 5: "Fri", 6: "Sat", 7: "Sun"}
        print("\nweekly shape (mean tps per weekday, all services):")
        for row in weekly:
            bar = "#" * int(float(row["avg_tps"]) * 1.5)
            print(f"  {names[row['dow']]}  {float(row['avg_tps']):6.2f}  {bar}")


async def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--days",
        type=int,
        default=28,
        help=(
            "Days of history to generate. 28 gives four weekly cycles, so module 5 can hold "
            "one back and still train on three. Fewer than 14 cannot validate weekly "
            "seasonality at all."
        ),
    )
    parser.add_argument(
        "--clear", action="store_true", help="delete previously replayed rows and exit"
    )
    parser.add_argument(
        "--no-smooth",
        action="store_true",
        help="skip the rate5m-equivalent smoothing (leaves the series noisier than live)",
    )
    parser.add_argument(
        "--skip-refresh",
        action="store_true",
        help="do not materialise the continuous aggregates (module 5 will see almost nothing)",
    )
    args = parser.parse_args()

    if args.days > 30:
        print(
            "Refusing: add_retention_policy('service_metrics', INTERVAL '30 days') would "
            "drop the oldest rows almost immediately. Use 28 or fewer."
        )
        return 1

    db = Database()
    await db.connect()
    try:
        if args.clear:
            await clear(db)
            await report(db)
            return 0

        result = await replay(db, days=args.days, smooth=not args.no_smooth)
        print(
            f"\nWrote {result.rows} rows across {result.points} points "
            f"for {result.services} services."
        )
        if args.skip_refresh:
            print("Skipped aggregate refresh; service_metrics_1h will be nearly empty.")
        else:
            print("Materialising rollups across the full range (this is the slow part)...")
            await refresh_aggregates(db, result.start, result.end)
        await report(db)
        print("\nDone. The metrics agent keeps the last hour; replay owns everything before.")
        return 0
    finally:
        await db.close()


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
